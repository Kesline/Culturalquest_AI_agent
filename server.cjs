
const http = require("node:http");
const { spawn } = require("node:child_process");
const { StringDecoder } = require("node:string_decoder");
const path = require("node:path");

const ROOT = __dirname;
const PORT = 8787;
const FRONTEND = "http://localhost:5173";

let agent = null;
let generation = 0;

function emptyTask() {
  return {
    status: "idle",
    question: null,
    answer: "",
    error: "",
  };
}

let task = emptyTask();

// --------------------------------------------------
// Communicate with Pi through JSON lines
// --------------------------------------------------

function sendToPi(process, data) {
  if (!process || !process.stdin.writable) {
    throw new Error("Pi is not running.");
  }

  process.stdin.write(JSON.stringify(data) + "\n");
}

// --------------------------------------------------
// Process AI events
// --------------------------------------------------

function handleEvent(event, currentGeneration) {
  // Ignore events from old AI sessions.
  if (currentGeneration !== generation) {
    return;
  }

  // Display questions generated by ask_user.
  if (event.type === "extension_ui_request") {
    if (
      event.method === "select" ||
      event.method === "input"
    ) {
      task.question = {
        id: event.id,
        method: event.method,
        title: event.title || "CultureQuest has a question",
        options: event.options || [],
      };

      task.status = "waiting";
    }

    return;
  }

  // Capture streamed AI recommendations.
  if (event.type === "message_update") {
    const update = event.assistantMessageEvent;

    if (
      update?.type === "text_delta" &&
      typeof update.delta === "string"
    ) {
      task.answer += update.delta;
    }

    return;
  }

  // Detect errors reported by the AI model.
  if (
    event.type === "message_end" &&
    event.message?.role === "assistant"
  ) {
    if (event.message.stopReason === "error") {
      task.error =
        event.message.errorMessage ||
        "The AI model returned an error.";

      task.status = "error";
    }

    return;
  }

  // Detect RPC command errors.
  if (event.type === "response" && event.success === false) {
    task.error =
      typeof event.error === "string"
        ? event.error
        : JSON.stringify(event.error || "Unknown RPC error");

    task.status = "error";
    return;
  }

  // The agent has finished answering.
  if (
    event.type === "agent_settled" ||
    event.type === "agent_end"
  ) {
    if (task.status === "waiting") {
      return;
    }

    if (task.status !== "error") {
      task.status = "done";
    }
  }
}

// --------------------------------------------------
// Start a fresh Pi agent
// --------------------------------------------------

function startAgent(prompt) {
  // Every request gets a unique generation number.
  generation += 1;

  const currentGeneration = generation;
  const oldAgent = agent;

  // Reset state before starting the new agent.
  task = {
    status: "starting",
    question: null,
    answer: "",
    error: "",
  };

  agent = null;

  // Shut down the previous process intentionally.
  if (oldAgent && !oldAgent.killed) {
    oldAgent.kill("SIGTERM");
  }

  const piProcess = spawn(
    "pi",
    [
      "--mode",
      "rpc",
      "--no-session",
      "--provider",
      "openrouter",
      "--model",
      "openrouter/free",
      "-e",
      "./extensions/ask-user.ts",
    ],
    {
      cwd: ROOT,
      stdio: ["pipe", "pipe", "pipe"],
      env: process.env,
    }
  );

  agent = piProcess;

  const decoder = new StringDecoder("utf8");
  let buffer = "";

  function processLine(line) {
    const cleaned = line.endsWith("\r")
      ? line.slice(0, -1)
      : line;

    if (!cleaned.trim()) {
      return;
    }

    try {
      const event = JSON.parse(cleaned);
      handleEvent(event, currentGeneration);
    } catch {
      console.log(
        "[Pi output]",
        cleaned.slice(0, 300)
      );
    }
  }

  function readLines(text) {
    buffer += text;

    let index;

    while ((index = buffer.indexOf("\n")) !== -1) {
      const line = buffer.slice(0, index);
      buffer = buffer.slice(index + 1);

      processLine(line);
    }
  }

  // Read Pi's responses.
  piProcess.stdout.on("data", (chunk) => {
    readLines(decoder.write(chunk));
  });

  piProcess.stdout.on("end", () => {
    readLines(decoder.end());

    if (buffer.trim()) {
      processLine(buffer);
    }

    buffer = "";
  });

  // Display Pi errors in the backend terminal.
  piProcess.stderr.on("data", (chunk) => {
    if (currentGeneration === generation) {
      console.error("[Pi]", chunk.toString());
    }
  });

  // Send the prompt after Pi starts.
  piProcess.on("spawn", () => {
    if (currentGeneration !== generation) {
      return;
    }

    try {
      task.status = "thinking";

      sendToPi(piProcess, {
        id: `prompt-${currentGeneration}`,
        type: "prompt",
        message: prompt,
      });
    } catch (error) {
      task.error = error.message;
      task.status = "error";
    }
  });

  piProcess.on("error", (error) => {
    // Ignore errors belonging to an older process.
    if (currentGeneration !== generation) {
      return;
    }

    task.error = error.message;
    task.status = "error";

    if (agent === piProcess) {
      agent = null;
    }
  });

  piProcess.on("exit", (code, signal) => {
    console.log(
      `[Pi] Session ${currentGeneration} exited`,
      { code, signal }
    );

    // The most important fix:
    // An old process must NEVER change the new task.
    if (currentGeneration !== generation) {
      return;
    }

    if (agent === piProcess) {
      agent = null;
    }

    // SIGTERM is expected when replacing a session.
    // If the active process stops, however, report it.
    if (task.status !== "done" && task.status !== "error") {
      task.error =
        signal === "SIGTERM" || code === 143
          ? "The current AI session was stopped."
          : `Pi exited unexpectedly (${signal || code}).`;

      task.status = "error";
    }
  });

  return piProcess;
}

// --------------------------------------------------
// HTTP helpers
// --------------------------------------------------

function sendJSON(res, data, status = 200) {
  res.writeHead(status, {
    "Content-Type": "application/json; charset=utf-8",
    "Access-Control-Allow-Origin": FRONTEND,
    "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
    "Access-Control-Allow-Headers": "Content-Type",
    "Cache-Control": "no-store",
  });

  res.end(JSON.stringify(data));
}

function readBody(req) {
  return new Promise((resolve, reject) => {
    let body = "";
    let rejected = false;

    req.on("data", (chunk) => {
      if (rejected) return;

      body += chunk.toString();

      if (body.length > 16000) {
        rejected = true;
        reject(new Error("Request is too large."));
      }
    });

    req.on("end", () => {
      if (rejected) return;

      try {
        resolve(JSON.parse(body || "{}"));
      } catch {
        reject(new Error("Invalid JSON request."));
      }
    });

    req.on("error", reject);
  });
}

// --------------------------------------------------
// Build the cultural discovery prompt
// --------------------------------------------------

function buildPrompt(city, budget, interests) {
  return `
You are CultureQuest, a human-in-the-loop AI
cultural discovery assistant.

Your purpose is to help someone experience the
world through books, food, music, poetry,
languages, and travel.

USER PREFERENCES

Destination: ${city}
Approximate budget: $${budget} USD
Selected interests: ${interests.join(", ")}

YOUR TASK

1. You MUST use the registered ask_user tool
   before creating the itinerary.

2. Ask the user which cultural experience
   they would like to prioritize.

3. Provide relevant options based on the
   interests the user selected.

4. Wait for the user to make a decision.

5. Use their chosen answer to continue.

6. Create a personalized cultural adventure
   with three recommended activities.

7. Suggest an approximate budget breakdown.

8. Include two useful phrases in the
   local language, with English translations.

9. Include a creative poetry or travel
   journaling prompt.

10. Make the recommendations specific
    to the chosen destination and preference.

IMPORTANT RULES

- Do not assume the user's preferences.
- Respect the user's actual decision.
- Do not invent verified restaurant details,
  exact prices, opening hours, or events.
- Explain when information is unverified.
- Do not modify files or execute commands.
- Keep the final response concise and readable.
`;
}

// --------------------------------------------------
// Local HTTP server
// --------------------------------------------------

const server = http.createServer(async (req, res) => {
  const origin = req.headers.origin;

  // Only accept requests from the local frontend.
  if (origin && origin !== FRONTEND) {
    return sendJSON(
      res,
      { error: "Origin not allowed." },
      403
    );
  }

  if (req.method === "OPTIONS") {
    return sendJSON(res, {});
  }

  // Return current AI state.
  if (
    req.method === "GET" &&
    req.url === "/api/state"
  ) {
    return sendJSON(res, task);
  }

  // Start a new recommendation.
  if (
    req.method === "POST" &&
    req.url === "/api/start"
  ) {
    try {
      const body = await readBody(req);

      const city = String(body.city || "")
        .trim()
        .slice(0, 150);

      const budget = Number(body.budget);

      const allowedInterests = [
        "Books",
        "Food",
        "Music",
        "Languages",
        "Travel",
        "Poetry",
      ];

      const interests = Array.isArray(body.interests)
        ? [...new Set(
            body.interests.filter((interest) =>
              allowedInterests.includes(interest)
            )
          )]
        : [];

      if (
        !city ||
        !Number.isFinite(budget) ||
        budget < 0 ||
        interests.length === 0
      ) {
        return sendJSON(
          res,
          {
            error:
              "Please provide a valid city, budget, and interests.",
          },
          400
        );
      }

      const prompt = buildPrompt(
        city,
        budget,
        interests
      );

      startAgent(prompt);

      return sendJSON(res, {
        ok: true,
        message: "CultureQuest AI started.",
      });
    } catch (error) {
      return sendJSON(
        res,
        { error: error.message },
        500
      );
    }
  }

  // Return the user's selection to ask_user.
  if (
    req.method === "POST" &&
    req.url === "/api/answer"
  ) {
    try {
      const body = await readBody(req);

      if (
        task.status !== "waiting" ||
        !task.question
      ) {
        return sendJSON(
          res,
          { error: "No pending AI question." },
          409
        );
      }

      const pendingQuestion = task.question;
      const answer = String(body.answer ?? "");

      if (
        !body.cancelled &&
        pendingQuestion.method === "select" &&
        !pendingQuestion.options.includes(answer)
      ) {
        return sendJSON(
          res,
          { error: "Invalid selection." },
          400
        );
      }

      sendToPi(agent, {
        type: "extension_ui_response",
        id: pendingQuestion.id,
        ...(body.cancelled
          ? { cancelled: true }
          : { value: answer }),
      });

      task.question = null;
      task.status = "thinking";

      return sendJSON(res, {
        ok: true,
        message: "Answer returned to Pi.",
      });
    } catch (error) {
      return sendJSON(
        res,
        { error: error.message },
        500
      );
    }
  }

  return sendJSON(
    res,
    { error: "Endpoint not found." },
    404
  );
});

// --------------------------------------------------
// Start local server
// --------------------------------------------------

server.listen(PORT, "127.0.0.1", () => {
  console.log("");
  console.log("CultureQuest AI backend is running!");
  console.log(`http://localhost:${PORT}`);
  console.log("");
  console.log("Using:");
  console.log("Pi Coding Agent");
  console.log("OpenRouter free model router");
  console.log("CultureQuest ask_user extension");
  console.log("");
});
